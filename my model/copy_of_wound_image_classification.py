def load_and_preprocess_data(img_dir, mask_dir):
    """
    Loads images and masks from specific directories, applies preprocessing.
    """
    images = []
    masks = []

    if not os.path.exists(img_dir):
        print(f"Error: Directory not found -> {img_dir}")
        return np.array(images), np.array(masks)

    image_filenames = sorted(os.listdir(img_dir))
    print(f"Processing {len(image_filenames)} images from {img_dir}...")

    for img_name in image_filenames:
        img_path = os.path.join(img_dir, img_name)
        mask_path = os.path.join(mask_dir, img_name)

        if os.path.exists(mask_path):
            # 1. Image Preprocessing
            img = cv2.imread(img_path)
            if img is not None:
                img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)
                img = cv2.resize(img, (IMG_SIZE, IMG_SIZE))
                img = cv2.GaussianBlur(img, (3, 3), 0)
                img = img / 255.0

                # 2. Mask Preprocessing
                mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
                mask = cv2.resize(mask, (IMG_SIZE, IMG_SIZE))
                mask = mask / 255.0
                mask = np.expand_dims(mask, axis=-1)

                images.append(img)
                masks.append(mask)
        else:
            print(f"Warning: Mask not found for image {img_name}")

    return np.array(images), np.array(masks)

